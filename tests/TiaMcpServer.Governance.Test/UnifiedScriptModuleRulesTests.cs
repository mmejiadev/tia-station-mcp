using System;
using TiaMcpServer.Siemens;
using TiaMcpServer.UnifiedScripts;

namespace TiaMcpServer.Governance.Tests
{
    /// <remarks>Measured 2026-11-08 on TIA Portal V20: an import replaces a module without a word, and broken JavaScript imports and compiles.</remarks>
    [TestClass]
    public sealed class UnifiedScriptModuleRulesTests
    {
        private const string Code = "export function one() {\r\n  return 1;\r\n}\r\n";

        private const string GeneratedComment = "/*<auto-generated>\r\n***End of Global definition area***\r\nChanges to this comment may cause incorrect behavior during document based import.\r\n</auto-generated>*/\r\n";

        private static readonly string[] NoModules = Array.Empty<string>();

        private static readonly string[] OneModule = { "MG1" };

        [TestMethod]
        public void Check_ANewModule_Passes()
        {
            UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", Code, replace: false), OneModule);
        }

        [TestMethod]
        public void Check_NoWrite_IsRefused()
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(null!, NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
        }

        /// <remarks>The name is written unquoted as a YAML key, so anything else could change what TIA Portal reads.</remarks>
        [TestMethod]
        [DataRow("")]
        [DataRow("1Module")]
        [DataRow("Module One")]
        [DataRow("Module:\r\n  Other")]
        [DataRow("../Module")]
        [DataRow("Module\n")]
        [DataRow("null")]
        [DataRow("True")]
        [DataRow("CON")]
        [DataRow("lpt1")]
        public void Check_ANameAYamlKeyCannotHold_IsRefused(string name)
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite(name, Code, replace: false), NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
        }

        [TestMethod]
        public void Check_EmptyCode_IsRefused()
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", " ", replace: false), NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
        }

        [TestMethod]
        public void Check_CodeOverTheLimit_IsRefused()
        {
            var tooLong = new string('a', UnifiedScriptChecker.MaxLength + 1);

            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", tooLong, replace: false), NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
        }

        [TestMethod]
        public void Check_AModuleAlreadyThereCaseAside_IsRefusedUnlessAskedFor()
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("mg1", Code, replace: false), OneModule));

            Assert.AreEqual(PortalErrorCode.InvalidState, refusal.Code);
            StringAssert.Contains(refusal.Message, "without a word", StringComparison.Ordinal);
        }

        [TestMethod]
        public void Check_AModuleAlreadyThereAndReplaceAskedFor_Passes()
        {
            UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG1", Code, replace: true), OneModule);
        }

        /// <remarks>The form TIA Portal V20 exported; its import refuses a folder without this file.</remarks>
        [TestMethod]
        public void Description_AName_IsTheYamlTiaPortalExports()
        {
            var yaml = UnifiedScriptModuleRules.Description("MG1");

            Assert.AreEqual("#Version: 2.0\r\n\r\nScriptModules:\r\n  MG1:\r\n    ScriptFile: MG1.hmi.js\r\n", yaml);
        }

        /// <remarks>Measured 2026-11-08: TIA Portal keeps "default function ..." with no export, which does not parse.</remarks>
        [TestMethod]
        [DataRow("export default function () {}")]
        [DataRow("export default function two() {}")]
        [DataRow("  export default 5;")]
        [DataRow("var a = 1; export default a;")]
        public void Check_ADefaultExport_IsRefused(string code)
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", code, replace: false), NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
            StringAssert.Contains(refusal.Message, "export function", StringComparison.Ordinal);
        }

        /// <remarks>Measured 2026-11-08: TIA Portal exports the function as well, so the list would export it twice.</remarks>
        [TestMethod]
        [DataRow("function one() {}\r\nexport { one };")]
        [DataRow("export {one as uno};")]
        [DataRow("export * from 'Other';")]
        [DataRow("/* c */ export { a };")]
        public void Check_AnExportList_IsRefused(string code)
        {
            var refusal = Assert.ThrowsException<PortalException>(() => UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", code, replace: false), NoModules));

            Assert.AreEqual(PortalErrorCode.InvalidParams, refusal.Code);
        }

        [TestMethod]
        [DataRow("export const LIMIT = 10;")]
        [DataRow("export class Pump {}")]
        [DataRow("export async function one() {}")]
        [DataRow("var exported = 'export default';")]
        [DataRow("/*\r\nexport default function\r\n*/\r\nvar a = 1;")]
        [DataRow("exportdefault = 1;")]
        [DataRow("var a = { export: 1 };")]
        public void Check_AnExportTiaPortalKeeps_Passes(string code)
        {
            UnifiedScriptModuleRules.Check(new UnifiedScriptModuleWrite("MG_New", code, replace: false), NoModules);
        }

        [TestMethod]
        public void SyntaxCheckBody_ExportedDeclarations_LoseOnlyTheirExport()
        {
            var body = UnifiedScriptModuleRules.SyntaxCheckBody("export function one() {}\r\n  export const two = 2;\r\nvar exported = 1;\r\n");

            Assert.AreEqual("       function one() {}\r\n         const two = 2;\r\nvar exported = 1;\r\n", body);
        }

        [TestMethod]
        public void SyntaxCheckBody_AnExportLaterOnALine_IsBlanked()
        {
            var body = UnifiedScriptModuleRules.SyntaxCheckBody("/* api */ export function one() {}");

            Assert.AreEqual("/* api */        function one() {}", body);
        }

        /// <remarks>Left in, each of these is a syntax error in a function body, and a valid module would be refused.</remarks>
        [TestMethod]
        [DataRow("import * as Other from 'Other';\r\nvar a = 1;")]
        [DataRow("import { b, c } from \"Other\"\r\nvar a = 1;")]
        [DataRow("import 'Other';\r\nvar a = 1;")]
        public void SyntaxCheckBody_AnImport_IsBlanked(string code)
        {
            var body = UnifiedScriptModuleRules.SyntaxCheckBody(code);

            StringAssert.EndsWith(body, "\r\nvar a = 1;", StringComparison.Ordinal);
            Assert.AreEqual("var a = 1;", body.Trim());
        }

        /// <remarks>The lines TIA Portal's syntax check reports have to be the caller's.</remarks>
        [TestMethod]
        public void SyntaxCheckBody_AnImportOverSeveralLines_KeepsTheLines()
        {
            var body = UnifiedScriptModuleRules.SyntaxCheckBody("import {\r\n  b\r\n} from 'Other';\r\nvar a = 1;");

            Assert.AreEqual(3, body.Split('\n').Length - 1);
            StringAssert.EndsWith(body, "\r\nvar a = 1;", StringComparison.Ordinal);
            Assert.AreEqual("var a = 1;", body.Trim());
        }

        [TestMethod]
        public void SyntaxCheckBody_AWordOnlyStartingWithImportOrACall_IsLeftAlone()
        {
            var code = "important('a');\r\nimport('b');\r\nvar c = d.export;\r\n";

            Assert.AreEqual(code, UnifiedScriptModuleRules.SyntaxCheckBody(code));
        }

        /// <remarks>As measured 2026-11-08: a comment above the functions goes above the generated comment.</remarks>
        [TestMethod]
        public void HoldsCode_TheGeneratedCommentAndOtherLineEndings_StillHoldsIt()
        {
            Assert.IsTrue(UnifiedScriptModuleRules.HoldsCode(GeneratedComment + Code.Replace("\r\n", "\n"), Code));
        }

        [TestMethod]
        public void HoldsCode_WhatIsNotAFunctionMovedAboveTheFunctions_StillHoldsIt()
        {
            var written = "export function one() {\r\n  return 1;\r\n}\r\nvar shared = 3;\r\nexport function two() {\r\n  return shared;\r\n}\r\n";
            var heldByTia = "var shared = 3;\r\n" + GeneratedComment + "export function one() {\r\n  return 1;\r\n}\r\nexport function two() {\r\n  return shared;\r\n}\r\n";

            Assert.IsTrue(UnifiedScriptModuleRules.HoldsCode(heldByTia, written));
        }

        [TestMethod]
        public void HoldsCode_AFunctionGivenItsExportAndItsBraceMoved_StillHoldsIt()
        {
            Assert.IsTrue(UnifiedScriptModuleRules.HoldsCode(GeneratedComment + "export function one() { return 1; \r\n}\r\n", "function one() { return 1;}"));
        }

        /// <remarks>Sorting the words would call these the same.</remarks>
        [TestMethod]
        public void HoldsCode_TheSameWordsInAnotherOrder_DoesNotHoldIt()
        {
            Assert.IsFalse(UnifiedScriptModuleRules.HoldsCode(GeneratedComment + "export function one(a, b) {\r\n  return b - a;\r\n}\r\n", "export function one(a, b) {\r\n  return a - b;\r\n}\r\n"));
        }

        [TestMethod]
        public void HoldsCode_FunctionsInAnotherOrder_DoesNotHoldIt()
        {
            Assert.IsFalse(UnifiedScriptModuleRules.HoldsCode("export function two() {}\r\nexport function one() {}\r\n", "export function one() {}\r\nexport function two() {}\r\n"));
        }

        /// <remarks>Only a function gets its export from TIA Portal; screens importing the constant would break.</remarks>
        [TestMethod]
        public void HoldsCode_AConstantThatLostItsExport_DoesNotHoldIt()
        {
            Assert.IsFalse(UnifiedScriptModuleRules.HoldsCode("const LIMIT = 10;\r\n", "export const LIMIT = 10;\r\n"));
        }

        [TestMethod]
        public void HoldsCode_AFunctionExpressionAmongTheDefinitions_StillHoldsIt()
        {
            var code = "var f = function () {\r\n  return 1;\r\n};\r\nexport function one() {\r\n  return f();\r\n}\r\n";
            var heldByTia = "var f = function () {\r\n  return 1;\r\n};\r\n" + GeneratedComment + "export function one() {\r\n  return f();\r\n}\r\n";

            Assert.IsTrue(UnifiedScriptModuleRules.HoldsCode(heldByTia, code));
        }

        [TestMethod]
        public void Summary_AWrite_NamesTheCodeWithoutCarryingIt()
        {
            var summary = UnifiedScriptModuleRules.Summary(new UnifiedScriptModuleWrite("MG1", Code, replace: true));

            StringAssert.Contains(summary, "replacing", StringComparison.Ordinal);
            StringAssert.Contains(summary, $"{Code.Length} characters", StringComparison.Ordinal);
            StringAssert.Contains(summary, "SHA-256", StringComparison.Ordinal);
            Assert.IsFalse(summary.Contains("return 1"), summary);
        }

        [TestMethod]
        public void HoldsCode_OtherCode_DoesNotHoldIt()
        {
            Assert.IsFalse(UnifiedScriptModuleRules.HoldsCode(GeneratedComment + "export function one() {\r\n  return 2;\r\n}\r\n", Code));
        }

        [TestMethod]
        public void HoldsCode_ALineMissing_DoesNotHoldIt()
        {
            Assert.IsFalse(UnifiedScriptModuleRules.HoldsCode(GeneratedComment + "export function one() {\r\n}\r\n", Code));
        }
    }
}
